// 質問定義とGeminiプロンプト組み立て（設計書3-3, 3-4）。
//
// この5問は仮ではなく設計書での決定。変えるときは設計書を先に直す。

export const QUESTIONS = [
  "何を作って（演じて）いますか。ひとことで。",
  "その中で、いちばん手間がかかるのはどこですか。",
  "そこは、ひとりでできるまでどれくらいかかりましたか。",
  "よそと違うと思うのは、どんなところですか。",
  "はじめて見る人に、どこを見てほしいですか。",
];

// 掘り下げの質問を作るときだけ参考にする観点。本文には絶対に使わない
// （設計書3-4改。分野の一般知識を本文に混ぜると職人の言葉でなくなる）。
const DOMAIN_HINTS = `質問を作るときだけ参考にする観点（本文には使わない）：
- 工程の具体名（例：下地、研ぎ、燻し、地無し）
- 回数・時間・年数（例：20回重ねる、10年かかる）
- 材料の産地や状態
- 失敗しやすい条件（例：湿度が高い日は乾かない）`;

export function buildComposePrompt(name, answers, { allowFollowup }) {
  const qa = QUESTIONS.map(
    (q, i) => `Q${i + 1}: ${q}\nA${i + 1}: ${answers[i] || ""}`,
  ).join("\n\n");

  const followupRule = allowFollowup
    ? `この回答だけでは、当たり障りのない一般論でしか3文が書けないと判断した場合は、
文章を作らず、掘り下げの質問を1つだけ返してください。
質問は「もう少し詳しく」のような一般的なものではなく、
${name}のこの職人にしか答えられない具体的な質問にしてください。
下記の観点を参考にしてよいですが、これはあくまで質問を作るためのヒントです。

${DOMAIN_HINTS}`
    : `この段階では掘り下げの質問は返せません。情報が少ないままでも、
与えられた回答だけを使って簡潔に3文にまとめてください
（一般論や分野の知識を足して埋めないこと）。`;

  return `あなたは伝統工芸・伝統芸能の紹介文を書く編集者です。
以下は「${name}」の職人への質問と回答です。

${qa}

${followupRule}

厳守事項:
- 回答に書かれていないことを付け足さない。分野の一般知識は質問を作るためだけに使い、
  本文（ja / en）には一切書かない
- 文章を作る場合はちょうど3文にする
- 誇張しない、大げさな宣伝文にしない

出力は次のJSON形式のみ。説明や前置きは書かない。
文章を作れる場合：
{"ja": ["文1", "文2", "文3"], "en": ["sentence1", "sentence2", "sentence3"], "followup": null}
掘り下げが必要な場合：
{"ja": null, "en": null, "followup": {"index": 0, "question": "..."}}`;
}
