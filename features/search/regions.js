export function blockOf(prefecture) {
  const b = PREFECTURE_TO_BLOCK[prefecture];
  if (!b) throw new Error(`地方が特定できない都道府県です: ${prefecture}`);
  return b;
}

// 地方ごとの都道府県一覧（フィルタの連動用）
export function prefecturesByBlock() {
  const map = Object.fromEntries(BLOCKS.map((b) => [b, []]));
  for (const [pref, block] of Object.entries(PREFECTURE_TO_BLOCK)) {
    map[block].push(pref);
  }
  return map;
}

