// 検索語を含むシノニムを引く（部分一致）
// 例: 「夏に涼しげな器がほしい」→ ["夏","ガラス","竹","器","食器","陶器"]
export function expand(query, dict = SYNONYMS) {
  const hits = new Set();
  for (const [term, targets] of Object.entries(dict)) {
    if (query.includes(term)) targets.forEach((t) => hits.add(t));
  }
  return [...hits];
}
